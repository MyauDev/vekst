-- Codes are hierarchical: two characters per level, so a parent's code is its
-- child's minus the last two. Resolving them here rather than carrying a second
-- key in the seed keeps one thing true instead of two.
UPDATE categories AS c
   SET parent_id = p.id
  FROM categories AS p
 WHERE c.taxonomy_version = p.taxonomy_version
   AND c.org_id IS NULL AND p.org_id IS NULL
   AND length(c.code) > 2
   AND p.code = left(c.code, length(c.code) - 2);

-- ---------------------------------------------------------------------------
-- Row-level security, last.
-- ---------------------------------------------------------------------------

ALTER TABLE categories ENABLE ROW LEVEL SECURITY;
ALTER TABLE categories FORCE ROW LEVEL SECURITY;

-- Read: a row that is shared, or mine. Nothing else.
CREATE POLICY categories_read ON categories FOR SELECT
    USING (org_id IS NULL OR org_id = app_current_org());

-- Write: only mine, and only as mine. A shared row arrives by migration and
-- leaves by migration; the application can never create, rename or delete one.
CREATE POLICY categories_write ON categories FOR ALL
    USING      (org_id = app_current_org())
    WITH CHECK (org_id = app_current_org());

