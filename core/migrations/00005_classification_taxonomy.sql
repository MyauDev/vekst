-- Category taxonomy: the list of report lines a transaction can be classified
-- into. Change 3.1, capability `classification-taxonomy`.
--
-- This is the first table in the schema that is shared and tenant at once, and
-- that single property drives every decision below.
--
-- Its top two levels are accounting structure -- NET SALES, OPEX >
-- Administration, and the arithmetic that turns them into GM. They must be
-- identical for every customer or reports stop being comparable and the
-- formulas stop being trustworthy. Its leaves are particular to a business:
-- "IT Park - membership" is a Belarusian residency scheme, "Merch for
-- employees" is one company's habit. Twenty nodes are shared, eighty-one are
-- not.
--
-- So org_id is NULL on a shared row, and the read policy admits a row that is
-- shared *or* mine while the write policy admits only mine. Splitting them is
-- the whole point: one FOR ALL policy saying `org_id IS NULL OR org_id =
-- app_current_org()` would let vekst_app rewrite GM's formula for every
-- customer at once.
--
-- Content comes from eval/out/seed_categories.sql, generated by eval/emit.py
-- from the founder's P&L structure and the three categorisation files, and
-- measured against 4,508 real transactions. See eval/README.md.

-- +goose Up

CREATE TABLE categories (
    id               uuid        PRIMARY KEY DEFAULT gen_random_uuid(),
    taxonomy_version text        NOT NULL,

    -- NULL = shared by every organisation. Populated = this organisation's own.
    org_id           uuid        NULL REFERENCES organizations (id) ON DELETE RESTRICT,
    scope            text        NOT NULL CHECK (scope IN ('global', 'org')),

    -- Hierarchical: two characters per level, so a parent's code is its
    -- child's minus the last two. The seed relies on that to resolve parents
    -- without carrying a second key.
    code             text        NOT NULL,
    parent_id        uuid        NULL REFERENCES categories (id) ON DELETE RESTRICT,
    level            smallint    NOT NULL CHECK (level BETWEEN 1 AND 5),
    name             text        NOT NULL,

    pnl_section      text        NULL,
    is_pnl           boolean     NOT NULL DEFAULT true,
    is_leaf          boolean     NOT NULL,

    -- GM, NM, CM, IBT and NI are arithmetic over other lines. A transaction can
    -- never land in one, and change 3.2 must never be offered one as a target.
    is_computed      boolean     NOT NULL DEFAULT false,
    formula          text        NULL,

    -- Payroll is known, the department is not. КНП 332 says "wages" and cannot
    -- say whose; 44 rules and 150 Kazakh rows land here. The report shows the
    -- amount as its own line rather than attributing it to a department.
    requires_allocation boolean  NOT NULL DEFAULT false,

    created_at       timestamptz NOT NULL DEFAULT now(),

    CONSTRAINT categories_scope_matches_owner CHECK (
        (scope = 'global' AND org_id IS NULL) OR (scope = 'org' AND org_id IS NOT NULL)),
    CONSTRAINT categories_computed_has_formula CHECK (
        NOT is_computed OR (formula IS NOT NULL AND is_leaf = false)),

    -- NULLS NOT DISTINCT, or the uniqueness the seed depends on would not
    -- exist for exactly the rows that are shared with everybody: Postgres
    -- treats every NULL org_id as distinct otherwise, and two shared rows
    -- could take the same code.
    CONSTRAINT categories_code_unique
        UNIQUE NULLS NOT DISTINCT (taxonomy_version, org_id, code)
);

CREATE INDEX categories_tenant_idx ON categories (taxonomy_version, org_id);
CREATE INDEX categories_parent_idx ON categories (parent_id);

-- A parent is shared, or it is mine. Never another organisation's.
--
-- This cannot be a composite foreign key, which is what CLAUDE.md requires of
-- referential checks between tenant tables. The legitimate case is an
-- organisation's leaf hanging under a *shared* parent, whose org_id is NULL and
-- therefore never equals the child's. A composite key cannot say "shared or
-- mine".
--
-- A constraint trigger can. It runs as the table owner and sees every row, so
-- it enforces what the key cannot state -- and it closes the same oracle the
-- composite key exists to close, because naming another organisation's category
-- raises the identical error whether that category exists or not.
-- +goose StatementBegin
CREATE FUNCTION categories_parent_is_visible() RETURNS trigger
    LANGUAGE plpgsql
    AS $fn$
DECLARE
    parent_org uuid;
    found      boolean;
BEGIN
    IF NEW.parent_id IS NULL THEN
        RETURN NEW;
    END IF;

    SELECT org_id, true INTO parent_org, found
      FROM categories WHERE id = NEW.parent_id;

    -- One message for "does not exist" and for "belongs to someone else". A
    -- different message for each would report the existence of a row the
    -- caller may not read.
    IF NOT coalesce(found, false) OR (parent_org IS NOT NULL AND parent_org IS DISTINCT FROM NEW.org_id) THEN
        RAISE EXCEPTION 'category parent % is not visible to this organisation', NEW.parent_id
            USING ERRCODE = '23503';
    END IF;
    RETURN NEW;
END
$fn$;
-- +goose StatementEnd

CREATE CONSTRAINT TRIGGER categories_parent_is_visible
    AFTER INSERT OR UPDATE OF parent_id, org_id ON categories
    DEFERRABLE INITIALLY IMMEDIATE
    FOR EACH ROW EXECUTE FUNCTION categories_parent_is_visible();

